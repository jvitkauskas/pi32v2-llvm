using namespace llvm;

#define DEBUG_TYPE "mccodeemitter"

namespace {
class PI32V2MCCodeEmitter : public MCCodeEmitter {
  const MCInstrInfo &MCII;
  MCContext &Ctx;

public:
  PI32V2MCCodeEmitter(const MCInstrInfo &MCII, MCContext &Ctx)
      : MCII(MCII), Ctx(Ctx) {}

  void encodeInstruction(const MCInst &MI, SmallVectorImpl<char> &CB,
                         SmallVectorImpl<MCFixup> &Fixups,
                         const MCSubtargetInfo &STI) const override;

  // Generated by TableGen.
  uint64_t getBinaryCodeForInstr(const MCInst &MI,
                                 SmallVectorImpl<MCFixup> &Fixups,
                                 const MCSubtargetInfo &STI) const;

  uint64_t getMachineOpValue(const MCInst &MI, const MCOperand &MO,
                             SmallVectorImpl<MCFixup> &Fixups,
                             const MCSubtargetInfo &STI) const;

  uint64_t encodeTargetExpr(const MCInst &MI, unsigned OpNo, unsigned Width,
                            SmallVectorImpl<MCFixup> &Fixups,
                            const MCSubtargetInfo &STI) const;
  uint64_t encodeImmExpr(const MCInst &MI, unsigned OpNo, unsigned Width,
                         SmallVectorImpl<MCFixup> &Fixups,
                         const MCSubtargetInfo &STI) const;

#define PI32V2_GEN_ENCODER_DECLS
#include "PI32V2OperandsGen.inc"
};
} // namespace

void PI32V2MCCodeEmitter::encodeInstruction(const MCInst &MI,
                                            SmallVectorImpl<char> &CB,
                                            SmallVectorImpl<MCFixup> &Fixups,
                                            const MCSubtargetInfo &STI) const {
  uint64_t Bits = getBinaryCodeForInstr(MI, Fixups, STI);
  unsigned Words = MCII.get(MI.getOpcode()).getSize() / 2;
  for (unsigned K = 0; K < Words; ++K) {
    uint16_t W = Bits >> (16 * (Words - 1 - K));
    CB.push_back(char(W & 0xFF));
    CB.push_back(char(W >> 8));
  }
}

uint64_t PI32V2MCCodeEmitter::getMachineOpValue(
    const MCInst &MI, const MCOperand &MO, SmallVectorImpl<MCFixup> &Fixups,
    const MCSubtargetInfo &STI) const {
  if (MO.isReg())
    return Ctx.getRegisterInfo()->getEncodingValue(MO.getReg());
  if (MO.isImm())
    return static_cast<uint64_t>(MO.getImm());
  report_fatal_error("PI32V2: an expression where the instruction has no "
                     "fixup");
}

// An expression in the branch target: a fixup at the instruction's start.
uint64_t PI32V2MCCodeEmitter::encodeTargetExpr(
    const MCInst &MI, unsigned OpNo, unsigned Width,
    SmallVectorImpl<MCFixup> &Fixups, const MCSubtargetInfo &STI) const {
  int Kind = PI32V2::fixupKindForOperand(MI.getOpcode(), OpNo);
  if (Kind < 0)
    report_fatal_error("PI32V2: no fixup for this branch");
  Fixups.push_back(MCFixup::create(0, MI.getOperand(OpNo).getExpr(),
                                   MCFixupKind(Kind), /*PCRel=*/true));
  return 0;
}

// An expression in a constant: the 32-bit constant loads, and the length and
// shape of a block (resolved by the assembler).
uint64_t PI32V2MCCodeEmitter::encodeImmExpr(
    const MCInst &MI, unsigned OpNo, unsigned Width,
    SmallVectorImpl<MCFixup> &Fixups, const MCSubtargetInfo &STI) const {
  int Kind = PI32V2::fixupKindForOperand(MI.getOpcode(), OpNo);
  if (Kind < 0 || PI32V2::fixupLayout(Kind).PCRel) {
    Ctx.reportError(SMLoc(), "this instruction cannot take a symbol");
    return 0;
  }
  Fixups.push_back(MCFixup::create(0, MI.getOperand(OpNo).getExpr(),
                                   MCFixupKind(Kind), /*PCRel=*/false));
  return 0;
}

#define PI32V2_GEN_ENCODERS
#include "PI32V2OperandsGen.inc"

#include "PI32V2GenMCCodeEmitter.inc"

MCCodeEmitter *llvm::createPI32V2MCCodeEmitter(const MCInstrInfo &MCII,
                                               MCContext &Ctx) {
  return new PI32V2MCCodeEmitter(MCII, Ctx);
}
